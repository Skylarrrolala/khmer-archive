// Writes the guarded content update, its rollback and a read-only preflight
// into docs/v2/content/, from two committed inputs:
//   - production-snapshot-2026-11-21.json: the seven rows as they were read
//     (the "from" state of the update, the "to" state of the rollback);
//   - lib/exhibit-records.ts: the `checked` text each record was reviewed
//     against (the "to" state of the update).
// Run from the repo root:  node scripts/generate-content-update.ts
// It only writes SQL files; it never connects to a database.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { RECORDS } from "../lib/exhibit-records.ts";

type Text = { name_khmer: string; name_english: string; context: string; description: string };
type SnapshotRow = Text & {
  id: string;
  told_by: string;
  photo_url: string;
  created_at: string;
  contributor_id: null;
  status: "published";
};
type Step = { id: string; label: string; from: Text; to: Text; told_by: string; photo_url: string; created_at: string };

const CONTENT = new URL("../docs/v2/content/", import.meta.url);
export const SNAPSHOT: SnapshotRow[] = JSON.parse(
  readFileSync(new URL("production-snapshot-2026-11-21.json", CONTENT), "utf8"),
);
const TEXT = ["name_khmer", "name_english", "context", "description"] as const;
const COUNT = 7;

const text = (row: Text): Text => ({
  name_khmer: row.name_khmer,
  name_english: row.name_english,
  context: row.context,
  description: row.description,
});

function steps(direction: "update" | "rollback"): Step[] {
  if (SNAPSHOT.length !== COUNT) throw new Error(`snapshot must hold ${COUNT} rows`);
  return SNAPSHOT.map((row) => {
    if (row.contributor_id !== null || row.status !== "published") throw new Error(`${row.id}: not a researched row`);
    if (!Object.hasOwn(RECORDS, row.id)) throw new Error(`${row.id}: no editorial record`);
    const original = text(row);
    const reviewed = text(RECORDS[row.id].checked);
    if (JSON.stringify(original) === JSON.stringify(reviewed)) throw new Error(`${row.id}: nothing to change`);
    const [from, to] = direction === "update" ? [original, reviewed] : [reviewed, original];
    return { id: row.id, label: row.name_english.split(" — ")[0], from, to, told_by: row.told_by, photo_url: row.photo_url, created_at: row.created_at };
  });
}

/** A dollar-quoted literal; refuses text that would close its own quote. */
const lit = (value: string) => {
  if (value.includes("$v$")) throw new Error("dollar-quote collision");
  return `$v$${value}$v$`;
};

const PLAN_TABLE = `create temp table content_plan (
  id uuid primary key,
  label text not null,
${TEXT.map((c) => `  from_${c} text not null,`).join("\n")}
${TEXT.map((c) => `  to_${c} text not null,`).join("\n")}
  told_by text not null,
  photo_url text not null,
  created_at timestamptz not null
) on commit drop;

insert into content_plan values`;

function planInsert(rows: Step[]) {
  return rows
    .map((s) => `  ('${s.id}', ${lit(s.label)},\n` +
      TEXT.map((c) => `   ${lit(s.from[c])}`).join(",\n") + ",\n" +
      TEXT.map((c) => `   ${lit(s.to[c])}`).join(",\n") + ",\n" +
      `   ${lit(s.told_by)}, ${lit(s.photo_url)}, '${s.created_at}')`)
    .join(",\n") + ";";
}

// The full expected state of a row: its text, plus every field that must never move.
const state = (side: "from" | "to") =>
  TEXT.map((c) => `e.${c} = p.${side}_${c}`).join("\n      and ") +
  `\n      and e.told_by = p.told_by and e.photo_url = p.photo_url and e.created_at = p.created_at` +
  `\n      and e.contributor_id is null and e.status = 'published'`;

function transition(direction: "update" | "rollback"): string {
  const rows = steps(direction);
  const name = direction === "update" ? "Content update" : "Content rollback";
  const header = direction === "update"
    ? `-- CONTENT UPDATE — PROPOSAL ONLY, NOT APPLIED. Requires the founder's approval.
--
-- Moves the seven ownerless researched rows from the text recorded in
-- production-snapshot-2026-11-21.json to the reviewed \`checked\` text in
-- lib/exhibit-records.ts (including the rename of Num Kor to Num Akor Thnot).`
    : `-- CONTENT ROLLBACK — NOT APPLIED. Reverses proposed-content-update.sql exactly.
--
-- Moves the seven rows from the reviewed \`checked\` text back to the text
-- recorded in production-snapshot-2026-11-21.json.`;

  return `-- =============================================================================
${header}
-- Generated by scripts/generate-content-update.ts. Do not edit by hand;
-- tests/exhibit-records.test.ts fails if this file and its inputs differ.
--
-- All-or-nothing. In one transaction it:
--   1. locks the review history against concurrent writes (SHARE mode, held
--      until commit) and all seven rows against concurrent edits, then records
--      the complete review history;
--   2. requires all seven to exist and each to hold exactly its expected
--      starting state: Khmer name, English name, occasion, description, source
--      marker, photo, created_at, no owner, published;
--   3. updates under that same full condition and requires exactly 7 rows;
--   4. requires exactly the seven target ids to be present afterwards, each
--      with the exact expected result and unchanged protected fields, and the
--      review history identical, row for row and field for field;
--   5. commits only if every check passed.
-- Any missing or re-identified row, intervening edit, unexpected count or
-- history change raises an error inside the guarded block, so nothing is
-- written. Never touches any other row.
--
-- Run the whole file in the Supabase SQL editor (or psql -v ON_ERROR_STOP=1).
-- Check preflight-content-update.sql first. Do NOT run supabase/seed.sql.
-- =============================================================================

begin;

${PLAN_TABLE}
${planInsert(rows)}

do $guard$
declare
  expected constant int := ${COUNT};
  found_rows int;
  changed int;
  problem text;
begin
  -- 1. Lock: no other transaction may write review history until this one
  --    ends (SHARE blocks INSERT/UPDATE/DELETE, allows reads), and none may
  --    change a target row. Then record the complete history as it stands.
  lock table public.review_history in share mode;
  perform 1 from public.entries where id in (select id from content_plan) for update;
  create temp table history_before on commit drop as select * from public.review_history;

  -- 2. Every target present, and exactly in its expected starting state.
  select count(*) into found_rows from public.entries where id in (select id from content_plan);
  if found_rows <> expected then
    raise exception '${name} aborted: % of % target rows found; nothing was changed.', found_rows, expected;
  end if;
  select string_agg(p.label, ', ' order by p.label) into problem
    from content_plan p left join public.entries e on e.id = p.id
    -- "is not true" also catches a field that has become null.
    where e.id is null or (${state("from")}) is not true;
  if problem is not null then
    raise exception '${name} aborted: not in the expected starting state: %; nothing was changed.', problem;
  end if;

  -- 3. Change exactly these rows, still conditional on the full starting state.
  update public.entries e set
${TEXT.map((c) => `    ${c} = p.to_${c}`).join(",\n")}
    from content_plan p
    where e.id = p.id
      and ${state("from")};
  get diagnostics changed = row_count;
  if changed <> expected then
    raise exception '${name} aborted: % of % rows changed; nothing was changed.', changed, expected;
  end if;

  -- 4a. Identity: exactly the seven target ids are still present. An id
  --     changed underneath, or a row removed, shows up here rather than
  --     silently dropping out of the checks below.
  select count(distinct id) into found_rows from public.entries where id in (select id from content_plan);
  if found_rows <> expected then
    raise exception '${name} aborted: % of % target ids present afterwards; nothing was changed.', found_rows, expected;
  end if;

  -- 4b. Every planned id, joined from the plan side so none can be skipped,
  --     holds exactly its expected result with its protected fields unchanged.
  select string_agg(p.label, ', ' order by p.label) into problem
    from content_plan p left join public.entries e on e.id = p.id
    where e.id is null or (${state("to")}) is not true;
  if problem is not null then
    raise exception '${name} aborted: unexpected result for: %; nothing was changed.', problem;
  end if;

  -- 4c. Review history identical in content, not just in size: every column of
  --     every row, compared as a multiset in both directions. EXCEPT ALL
  --     treats NULLs as equal and does not depend on row order, so any
  --     inserted, removed or edited row (an id, entry, status, reviewer or
  --     timestamp) is caught.
  if exists (select * from history_before except all select * from public.review_history)
     or exists (select * from public.review_history except all select * from history_before) then
    raise exception '${name} aborted: review history changed; nothing was changed.';
  end if;
  raise notice '${name} verified: % rows changed.', changed;
end
$guard$;

commit;

-- Report (read-only, after commit).
select id, name_khmer, name_english, left(description, 60) as opening, context
from public.entries
where id in (${rows.map((s) => `'${s.id}'`).join(", ")})
order by created_at desc;
`;
}

function preflight(): string {
  const rows = steps("update");
  return `-- =============================================================================
-- PREFLIGHT — READ-ONLY. Shows, for each of the seven rows, whether it is
-- ready for proposed-content-update.sql (still the original text) or for
-- rollback-content-update.sql (holding the reviewed text). A row that is
-- neither has been edited or is in an unexpected state: stop, and re-review.
-- Ends with ROLLBACK, so it changes nothing.
-- Generated by scripts/generate-content-update.ts.
-- =============================================================================

begin;

${PLAN_TABLE}
${planInsert(rows)}

select p.label,
       e.id is not null as present,
       coalesce(${state("from").replaceAll("\n      ", " ")}, false) as ready_for_update,
       coalesce(${state("to").replaceAll("\n      ", " ")}, false) as ready_for_rollback
from content_plan p left join public.entries e using (id)
order by p.label;

rollback;
`;
}

export const renderUpdate = () => transition("update");
export const renderRollback = () => transition("rollback");
export const renderPreflight = () => preflight();

/** The seven snapshot rows as inserts, for disposable test databases only. */
export const snapshotFixtureSql = () =>
  SNAPSHOT.map((r) =>
    `insert into public.entries (id, name_khmer, name_english, told_by, context, description, photo_url, status, contributor_id, created_at)\n` +
    `values ('${r.id}', ${lit(r.name_khmer)}, ${lit(r.name_english)}, ${lit(r.told_by)}, ${lit(r.context)}, ${lit(r.description)}, ${lit(r.photo_url)}, 'published', null, '${r.created_at}');`,
  ).join("\n") + "\n";

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL("proposed-content-update.sql", CONTENT), renderUpdate());
  writeFileSync(new URL("rollback-content-update.sql", CONTENT), renderRollback());
  writeFileSync(new URL("preflight-content-update.sql", CONTENT), renderPreflight());
  console.log("wrote proposed-content-update.sql, rollback-content-update.sql, preflight-content-update.sql");
}
